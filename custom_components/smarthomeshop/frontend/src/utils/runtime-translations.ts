export const cardText = (hass: unknown, source: string): string => {
  const language = getLanguageFromHass(hass);
  return CARD_TRANSLATIONS[language]?.[source] || source;
};

const TEXT_STATE = new WeakMap<Text, { source: string; lastApplied: string }>();
const ATTRIBUTE_STATE = new WeakMap<Element, Map<string, { source: string; lastApplied: string }>>();
const TRANSLATABLE_ATTRIBUTES = ['aria-label', 'aria-description', 'title', 'placeholder', 'alt'] as const;

const translateTextNode = (node: Text, hass: unknown): void => {
  const parent = node.parentElement;
  if (!parent || parent.closest('[data-i18n-ignore], code, pre, script, style')) return;
  const current = node.data;
  const previous = TEXT_STATE.get(node);
  const sourceValue = previous && current === previous.lastApplied ? previous.source : current;
  const prefix = sourceValue.match(/^\s*/)?.[0] || '';
  const suffix = sourceValue.match(/\s*$/)?.[0] || '';
  const source = sourceValue.trim().replace(/\s+/g, ' ');
  if (!source) return;
  const next = `${prefix}${cardText(hass, source)}${suffix}`;
  TEXT_STATE.set(node, { source: sourceValue, lastApplied: next });
  if (current !== next) node.data = next;
};

const translateAttributes = (element: Element, hass: unknown): void => {
  let states = ATTRIBUTE_STATE.get(element);
  if (!states) {
    states = new Map();
    ATTRIBUTE_STATE.set(element, states);
  }
  for (const attribute of TRANSLATABLE_ATTRIBUTES) {
    if (!element.hasAttribute(attribute)) continue;
    const current = element.getAttribute(attribute) || '';
    const previous = states.get(attribute);
    const source = previous && current === previous.lastApplied ? previous.source : current;
    const next = cardText(hass, source);
    states.set(attribute, { source, lastApplied: next });
    if (current !== next) element.setAttribute(attribute, next);
  }
};

type LocalizedHost = ReactiveControllerHost & { renderRoot: HTMLElement | DocumentFragment };

export class CardLocalizationController implements ReactiveController {
  private readonly host: LocalizedHost;
  private readonly hassProvider: () => LanguageHass | undefined;
  private observers = new Set<MutationObserver>();
  private observedRoots = new WeakSet<ShadowRoot>();
  private scheduledRoots = new WeakSet<ShadowRoot>();

  public constructor(host: LocalizedHost, hassProvider: () => LanguageHass | undefined) {
    this.host = host;
    this.hassProvider = hassProvider;
    host.addController(this);
  }

  public hostUpdated(): void {
    const root = this.host.renderRoot;
    if (root instanceof ShadowRoot) this.observeRoot(root);
    if (root instanceof ShadowRoot) this.localizeRoot(root);
  }

  public hostDisconnected(): void {
    for (const observer of this.observers) observer.disconnect();
    this.observers.clear();
    this.observedRoots = new WeakSet();
    this.scheduledRoots = new WeakSet();
  }

  private localizeRoot(root: ShadowRoot): void {
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    let node = walker.nextNode();
    while (node) {
      translateTextNode(node as Text, this.hassProvider());
      node = walker.nextNode();
    }
    for (const element of Array.from(root.querySelectorAll('*'))) {
      translateAttributes(element, this.hassProvider());
      if (element.shadowRoot) this.observeRoot(element.shadowRoot);
    }
  }

  private schedule(root: ShadowRoot): void {
    if (this.scheduledRoots.has(root)) return;
    this.scheduledRoots.add(root);
    queueMicrotask(() => {
      this.scheduledRoots.delete(root);
      this.localizeRoot(root);
    });
  }

  private observeRoot(root: ShadowRoot): void {
    if (this.observedRoots.has(root)) return;
    this.observedRoots.add(root);
    const observer = new MutationObserver(() => this.schedule(root));
    observer.observe(root, {
      subtree: true,
      childList: true,
      characterData: true,
      attributes: true,
      attributeFilter: [...TRANSLATABLE_ATTRIBUTES],
    });
    this.observers.add(observer);
    this.localizeRoot(root);
  }
}

